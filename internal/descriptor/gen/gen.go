// Package gen renders the generated kong subcommand tree from the descriptor's cli blocks
// (docs/CLI-DESIGN.md §4). The descriptor stays the single source of truth: `go generate`
// writes cmd/safe_cli/zz_generated_tree.go from Source, and a test fails when the committed
// file drifts from what the descriptor would generate.
//
// Generated verb structs use POINTER fields with NO kong defaults: nil means the flag was not
// given, and the engine applies the descriptor's defaults itself, so select flag:, nulls and
// excludes act on explicit presence. Enums are listed in the help and enforced by the engine.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/ejc3/safe_cli/internal/descriptor"
)

// verb is one generated command: which op/block it came from and its resolved shape.
type verb struct {
	entity, op string
	area, name string
	block      *descriptor.CLI
	childFlag  bool // takes --child (target child/device, or a select branch does)
	device     bool // target device: offers --allow-unpaired
	confirm    bool // destructive op or live_emergency verb: --confirm is required
}

// Source renders the Go source of the generated tree for d.
func Source(d *descriptor.Descriptor) ([]byte, error) {
	areas := map[string][]verb{}
	for _, ename := range d.EntityNames() {
		e := d.Entities[ename]
		collect := func(ops map[string]descriptor.Operation) error {
			names := make([]string, 0, len(ops))
			for k := range ops {
				names = append(names, k)
			}
			sort.Strings(names)
			for _, oname := range names {
				o := ops[oname]
				if !o.Available() {
					continue
				}
				for _, b := range o.CLI {
					if b.Verb == "" {
						continue
					}
					if b.Group != "" {
						return fmt.Errorf("%s.%s: a third level (group %q) is not generated yet", ename, oname, b.Group)
					}
					if _, ok := d.Areas[b.Area]; !ok {
						return fmt.Errorf("%s.%s: area %q has no help text in the descriptor's areas map", ename, oname, b.Area)
					}
					v := verb{entity: ename, op: oname, area: b.Area, name: b.Verb, block: b, confirm: o.Destructive || b.LiveEmergency}
					v.childFlag = b.Target == "child" || b.Target == "device"
					v.device = b.Target == "device"
					for _, r := range b.Select {
						if r.Target == "child" || r.Target == "device" {
							v.childFlag = true
						}
						if r.Target == "device" {
							v.device = true // the engine applies the selected device contract
						}
						// The engine demands --confirm for whichever op is selected, so a
						// destructive branch makes the flag necessary on the verb.
						if bo, ok := d.LookupOp(r.Op); ok && bo.Destructive {
							v.confirm = true
						}
					}
					areas[b.Area] = append(areas[b.Area], v)
				}
			}
			return nil
		}
		if err := collect(e.Operations); err != nil {
			return nil, err
		}
		if err := collect(e.Actions); err != nil {
			return nil, err
		}
	}
	areaNames := make([]string, 0, len(areas))
	for a := range areas {
		areaNames = append(areaNames, a)
	}
	sort.Strings(areaNames)

	var w bytes.Buffer
	w.WriteString("// Code generated by internal/descriptor/gen from verizon_family.json; DO NOT EDIT.\n\n")
	w.WriteString("package main\n\n")
	w.WriteString("// generatedAreas is the subcommand tree docs/CLI-DESIGN.md describes: one area per\n")
	w.WriteString("// command group, one verb per cli block, every flag typed. It is embedded in CLI.\n")
	w.WriteString("type generatedAreas struct {\n")
	for _, a := range areaNames {
		fmt.Fprintf(&w, "\t%s %sArea `cmd:\"\" name:%s help:%s`\n", ident(a), ident(a), tagQuote(a), tagQuote(d.Areas[a]))
	}
	w.WriteString("}\n\n")
	for _, a := range areaNames {
		vs := areas[a]
		sort.SliceStable(vs, func(i, j int) bool {
			pi, pj := priorityRank(vs[i].block.Priority), priorityRank(vs[j].block.Priority)
			if pi != pj {
				return pi < pj
			}
			return vs[i].name < vs[j].name
		})
		fmt.Fprintf(&w, "// %sArea groups the %s verbs (core verbs first).\n", ident(a), a)
		fmt.Fprintf(&w, "type %sArea struct {\n", ident(a))
		for _, v := range vs {
			fmt.Fprintf(&w, "\t%s %s `cmd:\"\" name:%s help:%s`\n", ident(v.name), structName(v), tagQuote(v.name), tagQuote(verbHelp(v)))
		}
		w.WriteString("}\n\n")
		for _, v := range vs {
			if err := writeVerb(&w, v); err != nil {
				return nil, err
			}
		}
	}
	src, err := format.Source(w.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated source does not compile: %w\n%s", err, w.String())
	}
	return src, nil
}

func priorityRank(p string) int {
	switch p {
	case "core":
		return 0
	case "common":
		return 1
	}
	return 2
}

func structName(v verb) string { return ident(v.area) + ident(v.name) + "Cmd" }

// writeVerb emits one verb's struct (flags as pointer fields), its help, and a Run that
// gathers the flags the user gave and hands them to runVerb.
func writeVerb(w *bytes.Buffer, v verb) error {
	b := v.block
	fmt.Fprintf(w, "// %s: %s %s <- %s.%s\n", structName(v), v.area, v.name, v.entity, v.op)
	fmt.Fprintf(w, "type %s struct {\n", structName(v))
	if v.childFlag {
		req, tag := "Required.", ` required:""`
		if b.Target != "child" && b.Target != "device" {
			req, tag = "Optional: selects the per-child form.", ""
		}
		fmt.Fprintf(w, "\tChild *string `name:\"child\" help:%s%s`\n", tagQuote("The child, by the SERVICE-ID that `safe_cli members` prints. "+req), tag)
	}
	for _, f := range b.Flags {
		goType, err := goFieldType(f)
		if err != nil {
			return fmt.Errorf("%s.%s --%s: %w", v.entity, v.op, f.Name, err)
		}
		tags := fmt.Sprintf("name:%s help:%s", tagQuote(f.Name), tagQuote(flagHelp(f)))
		if strings.HasPrefix(goType, "[]") {
			tags += ` sep:"none"`
		}
		if f.Required {
			tags += ` required:""`
		}
		fmt.Fprintf(w, "\t%s %s `%s`\n", ident(f.Name), goType, tags)
	}
	fmt.Fprintf(w, "\tDryRun bool `name:\"dry-run\" help:\"Print the exact request, with the resolved ids, without sending it.\"`\n")
	if v.confirm {
		why := "this verb is destructive and effectively irreversible"
		if b.LiveEmergency {
			why = "this verb triggers a LIVE emergency/dispatch flow on a real account"
		}
		fmt.Fprintf(w, "\tConfirm bool `name:\"confirm\" help:%s`\n", tagQuote("Required: "+why+"."))
	}
	if v.device {
		fmt.Fprintf(w, "\tAllowUnpaired bool `name:\"allow-unpaired\" help:\"Send even though the child's device is not PAIRED.\"`\n")
	}
	w.WriteString("}\n\n")
	// Help for the verb itself comes from the parent's cmd tag; kong shows it before flags.
	fmt.Fprintf(w, "func (c *%s) Run(rc *runContext) error {\n", structName(v))
	w.WriteString("\tgiven := map[string]any{}\n")
	for _, f := range b.Flags {
		goType, _ := goFieldType(f)
		field := ident(f.Name)
		if strings.HasPrefix(goType, "[]") {
			fmt.Fprintf(w, "\tif c.%s != nil {\n\t\tgiven[%q] = c.%s\n\t}\n", field, f.Name, field)
		} else {
			fmt.Fprintf(w, "\tif c.%s != nil {\n\t\tgiven[%q] = *c.%s\n\t}\n", field, f.Name, field)
		}
	}
	child := `""`
	if v.childFlag {
		child = "deref(c.Child)"
	}
	confirm := "false"
	if v.confirm {
		confirm = "c.Confirm"
	}
	allow := "false"
	if v.device {
		allow = "c.AllowUnpaired"
	}
	fmt.Fprintf(w, "\treturn runVerb(rc, %q, %q, %q, %q, given, %s, c.DryRun, %s, %s)\n}\n\n", v.entity, v.op, v.area, v.name, child, confirm, allow)
	return nil
}

// verbHelp is the summary plus the prerequisite lines an agent must see before calling
// (D6): kong prints it as the command description in `<area> <verb> --help`.
func verbHelp(v verb) string {
	help := v.block.Summary
	for _, p := range v.block.Prereq {
		help += "\nPrerequisite: " + p
	}
	if v.device {
		help += "\nAn UNPAIRED target is refused; pass --allow-unpaired to send anyway."
	}
	if v.confirm {
		help += "\nRequires --confirm."
	}
	return help
}

// flagHelp is the descriptor's help plus the enum and default when the text does not
// already state them (D5: every flag's help states its default and effect).
func flagHelp(f descriptor.Flag) string {
	h := strings.ReplaceAll(f.Help, "`", "'")
	if len(f.Enum) > 0 && !strings.Contains(h, strings.Join(f.Enum, "|")) {
		h += " One of " + strings.Join(f.Enum, "|") + "."
	}
	if f.Default != nil && !strings.Contains(strings.ToLower(h), "default") {
		h += fmt.Sprintf(" (default: %v)", f.Default)
	}
	if f.Repeatable {
		h += " Repeatable."
	}
	return h
}

func goFieldType(f descriptor.Flag) (string, error) {
	if f.Repeatable || f.Type == "list" {
		return "[]string", nil
	}
	switch f.Type {
	case "string", "enum", "duration", "date", "datetime", "tz":
		return "*string", nil
	case "int":
		return "*int64", nil
	case "float":
		return "*float64", nil
	case "bool":
		return "*bool", nil
	}
	return "", fmt.Errorf("no Go type for flag type %q", f.Type)
}

// ident turns a kebab-case name into an exported Go identifier (pause-internet -> PauseInternet).
func ident(kebab string) string {
	var b strings.Builder
	for _, part := range strings.Split(kebab, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// tagQuote quotes s for use inside a raw-string struct tag: no backticks may appear.
func tagQuote(s string) string {
	return strconv.Quote(strings.ReplaceAll(s, "`", "'"))
}
